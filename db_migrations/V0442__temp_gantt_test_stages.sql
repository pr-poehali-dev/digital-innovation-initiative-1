-- ИСПРАВЛЕНО ПОСТФАКТУМ: исходная версия этого файла вставляла тестовые
-- этапы с жёстко заданным project_id=15 — проектом, который в реальности
-- был создан вручную через API в уже существующей БД, а не через
-- миграцию. На чистом развёртывании exec_project с id=15 к этому моменту
-- не существует, и вставка падала бы по FK exec_project_stage.project_id
-- REFERENCES exec_project(id) NOT NULL, останавливая ВСЮ последующую
-- цепочку миграций (V0443 и далее).
--
-- Исправление делает миграцию идемпотентной и безопасной в обоих случаях:
--   - на текущей БД, где проект id=15 уже существует (создан вручную,
--     помечен is_test_data) — UPDATE и INSERT выполняются как раньше;
--   - на чистом развёртывании, где id=15 не существует — WHERE EXISTS
--     не пропускает вставку, миграция проходит без ошибки, а сама
--     тестовая сцена просто не создаётся (что и требуется: сценарные
--     тестовые данные не должны быть обязательным условием применения
--     схемы).
--
-- Правильная стратегия на будущее: одноразовые сценарные тестовые данные
-- не должны попадать в db_migrations вообще — только в отдельный
-- сид/фикстуру вне продакшн-цепочки миграций схемы. Эта правка не
-- меняет номер версии и не переписывает историю — только делает
-- содержимое конкретного файла безопасным для повторного применения.

UPDATE exec_project SET is_test_data = true WHERE id = 15;

INSERT INTO exec_project_stage (project_id, title, sort_order, status, plan_start, plan_end, fact_start, fact_end)
SELECT * FROM (VALUES
  (15, 'Этап 1: Анализ требований', 10, 'done', '2026-09-01'::date, '2026-09-20'::date, '2026-09-01'::date, '2026-09-22'::date),
  (15, 'Этап 2: Разработка', 20, 'in_progress', '2026-09-21'::date, '2026-11-10'::date, '2026-09-23'::date, NULL::date),
  (15, 'Этап 3: Внедрение', 30, 'not_started', '2026-11-11'::date, '2026-12-15'::date, NULL::date, NULL::date)
) AS v(project_id, title, sort_order, status, plan_start, plan_end, fact_start, fact_end)
WHERE EXISTS (SELECT 1 FROM exec_project WHERE id = 15)
  AND NOT EXISTS (SELECT 1 FROM exec_project_stage WHERE project_id = 15);
