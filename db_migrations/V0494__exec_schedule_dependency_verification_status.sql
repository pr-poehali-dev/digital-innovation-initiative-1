-- Зависимости расписания, перенесённые из исходного материала (презентации,
-- дорожной карты) без подтверждения владельцем, могут содержать
-- противоречия (например, предшественник датирован позже последователя).
-- Такие связи не должны молча участвовать в расчёте критического пути —
-- нужен явный статус "черновик, требует подтверждения" вместо неявного
-- доверия любой сохранённой зависимости.
ALTER TABLE exec_schedule_dependency
    ADD COLUMN IF NOT EXISTS verification_status VARCHAR(32) NOT NULL DEFAULT 'confirmed',
    ADD CONSTRAINT chk_dependency_verification_status
        CHECK (verification_status IN ('draft', 'confirmed'));

COMMENT ON COLUMN exec_schedule_dependency.verification_status IS
    'draft — связь перенесена из источника автоматически и содержит нестыковку (например, даты предшественника и последователя противоречат порядку), требует подтверждения владельцем инициативы; confirmed — обычная действующая зависимость, участвует в расчёте критического пути. Черновые связи исключаются из CPM.';

-- Зависимости 1.1 → 1 и 1.2 → 1 инициативы 100401 (СУРР): даты
-- предшественников (30.10.2026) позже даты итоговой вехи (30.09.2026) —
-- прямое противоречие порядку FS, обнаруженное при переносе из презентации.
UPDATE exec_schedule_dependency
SET verification_status = 'draft'
WHERE id IN (11, 12) AND archived_at IS NULL;
