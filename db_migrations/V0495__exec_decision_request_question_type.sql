-- Вопросы руководителю бывают двух принципиально разных категорий:
--  * управленческое решение (например, прекратить инициативу или нет) —
--    требует стратегического выбора;
--  * уточнение исходных данных (противоречие в датах/зависимостях,
--    перенесённых из источника) — техническая правка, не решение по сути
--    инициативы. Смешивать их в одном списке вводит руководителя в
--    заблуждение о характере вопроса.
ALTER TABLE exec_initiative_decision_request
    ADD COLUMN IF NOT EXISTS question_type VARCHAR(32) NOT NULL DEFAULT 'decision',
    ADD CONSTRAINT chk_idr_question_type
        CHECK (question_type IN ('decision', 'data_clarification'));

COMMENT ON COLUMN exec_initiative_decision_request.question_type IS
    'decision — управленческое решение руководителя (стратегический выбор); data_clarification — уточнение исходных данных графика/дат у владельца инициативы, не является решением по существу инициативы.';

